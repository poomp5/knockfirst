export type StrKey = keyof typeof th;
type Vars = Record<string, string | number>;

const tables: Record<Lang, Record<StrKey, string>> = { th, en };
const STORAGE_KEY = "knockfirst.lang";

let lang: Lang = "th";
let loadPromise: Promise<void> | null = null;
const listeners = new Set<() => void>();

function subscribe(listener: () => void): () => void {
  listeners.add(listener);
  return () => {
    listeners.delete(listener);
  };
}
const getSnapshot = (): Lang => lang;

/** Translate for an explicit language. Missing key → Thai → the key itself (never throws). */
export function translate(l: Lang, key: StrKey, vars?: Vars): string {
  let s = tables[l][key] ?? th[key] ?? key;
  if (vars) for (const k in vars) s = s.split(`{${k}}`).join(String(vars[k]));
  return s;
}

/** Current-language translate for non-React code. Components should use useLang().t so they re-render. */
export function t(key: StrKey, vars?: Vars): string {
  return translate(lang, key, vars);
}

export function getLang(): Lang {
  return lang;
}

export function loadLang(): Promise<void> {
  if (!loadPromise) {
    loadPromise = (async () => {
      try {
        const saved = await AsyncStorage.getItem(STORAGE_KEY);
        if (saved === "th" || saved === "en") setLangState(saved);
      } catch (e) {
        console.warn("[i18n] read failed", e);
      }
    })();
  }
  return loadPromise;
}

function setLangState(l: Lang) {
  if (l === lang) return;
  lang = l;
  listeners.forEach((fn) => fn());
}

export async function setLang(l: Lang): Promise<void> {
  setLangState(l);
  try {
    await AsyncStorage.setItem(STORAGE_KEY, l);
  } catch (e) {
    console.warn("[i18n] save failed", e);
  }
}

// Contract label tables picked by language (contract.ts stays untouched).
export const statusLabel = (l: Lang) => (l === "en" ? STATUS_LABEL_EN : STATUS_LABEL_TH);
export const redFlagLabel = (l: Lang) => (l === "en" ? RED_FLAG_LABEL_EN : RED_FLAG_LABEL_TH);
export const riskLabel = (l: Lang) => (l === "en" ? RISK_LABEL_EN : RISK_LABEL_TH);
export const dateLocale = (l: Lang): Locale => (l === "en" ? enUS : thLocale);

export function useLang() {
  const l = useSyncExternalStore(subscribe, getSnapshot, getSnapshot);
  useEffect(() => {
    void loadLang();
  }, []);
  const tl = useCallback((key: StrKey, vars?: Vars) => translate(l, key, vars), [l]);
  return {
    lang: l,
    setLang,
    t: tl,
    statusLabel: statusLabel(l),
    redFlagLabel: redFlagLabel(l),
    riskLabel: riskLabel(l),
    dateLocale: dateLocale(l),
  };
}
